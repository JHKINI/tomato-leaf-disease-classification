    # 폴더 생성
    # ----------------------------------------

    for split in ["train", "val", "test"]:

        os.makedirs(
            os.path.join(
                OUTPUT_DIR,
                split,
                class_name
            ),
            exist_ok=True
        )

    # ----------------------------------------
    # 이미지 복사
    # ----------------------------------------

    split_data = {
        "train": train_images,
        "val": val_images,
        "test": test_images
    }

    for split, file_list in split_data.items():

        destination_dir = os.path.join(
            OUTPUT_DIR,
            split,
            class_name
        )

        for file in file_list:

            source_path = os.path.join(
                class_dir,
                file
            )

            destination_path = os.path.join(
                destination_dir,
                file
            )

            shutil.copy2(
                source_path,
                destination_path
            )

    total_count += len(selected_images)


